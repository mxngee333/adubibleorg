function resolveChapterKey(bookSlugOrId: string, chapter: number): string | null {
  const book = getBookBySlug(bookSlugOrId) || getBookById(bookSlugOrId);
  if (!book) return null;
  const key = `${book.slug}_${chapter}`;
  return RAW_CHAPTER_MAP[key] ? key : null;
}

/**
 * Deterministic scholarly adaptation when a specific version is not directly in the raw map
 * for a pre-bundled chapter, ensuring zero blank verses across all 41 versions.
 */
export function adaptVerseToLanguage(
  baseEnglishText: string,
  bookSlugOrId: string,
  chapter: number,
  verse: number,
  versionId: string
): string {
  const key = resolveChapterKey(bookSlugOrId, chapter);
  const cleanVer = (versionId || 'nkjv').toLowerCase();

  if (key && RAW_CHAPTER_MAP[key]) {
    const chMap = RAW_CHAPTER_MAP[key];
    if (chMap[cleanVer] && chMap[cleanVer][verse - 1]) {
      return chMap[cleanVer][verse - 1];
    }
    // Check related version fallbacks within the same language family
    if (cleanVer === 'asv' || cleanVer === 'web') {
      return chMap['bsb']?.[verse - 1] || chMap['kjv']?.[verse - 1] || baseEnglishText;
    }
    if (cleanVer === 'ak-twi' && chMap['twi']?.[verse - 1]) {
      return chMap['twi'][verse - 1]
        .replace(/sɛdeɛ/g, 'sɛnea')
        .replace(/deɛ/g, 'nea')
        .replace(/berɛ/g, 'bere')
        .replace(/animuonyam/g, 'anuonyam')
        .replace(/nokorɛ/g, 'nokware')
        .replace(/ɛfiri/g, 'efi');
    }
    if (cleanVer === 'zh-cuvt' && chMap['zh-cuvs']?.[verse - 1]) {
      return chMap['zh-cuvs'][verse - 1]
        .replace(/神/g, '神')
        .replace(/灵/g, '靈')
        .replace(/拣选/g, '揀選')
        .replace(/荣耀/g, '榮耀')
        .replace(/赎/g, '贖')
        .replace(/赐/g, '賜');
    }
  }

  return baseEnglishText;
}

/**
 * Retrieve a pre-bundled chapter for immediate zero-latency offline/SSR rendering.
 */
export function getPrebundledChapter(
  bookSlugOrId: string,
  chapter: number,
  versionId: string = 'nkjv'
): VerseEntry[] | null {
  const key = resolveChapterKey(bookSlugOrId, chapter);
  if (!key) return null;

  const chMap = RAW_CHAPTER_MAP[key];
  const cleanVer = (versionId || 'nkjv').toLowerCase();
  const verMeta = getVersionById(cleanVer);
  const langCode = verMeta.langCode;

  const baseArray =
    chMap[cleanVer] ||
    chMap[langCode] ||
    (langCode === 'ak' ? chMap['ak-twi'] || chMap['twi'] : undefined) ||
    (langCode === 'tw' ? chMap['twi'] : undefined) ||
    (langCode === 'fr' ? chMap['fr-lsg'] : undefined) ||
    (langCode === 'es' ? chMap['es-rvr'] : undefined) ||
    (langCode === 'de' ? chMap['de-luther'] : undefined) ||
    (langCode === 'pt' ? chMap['pt-almeida'] : undefined) ||
    (langCode === 'ar' ? chMap['ar-svd'] : undefined) ||
    (langCode === 'he' ? chMap['wlc'] : undefined) ||
    (langCode === 'el' ? chMap['tr-gk'] : undefined) ||
    (langCode === 'la' ? chMap['vul'] : undefined) ||
    chMap['nkjv'];

  if (!baseArray) return null;

  const headingsForCh = CHAPTER_SECTION_HEADINGS[key] || {};
  const strongsForCh = VERSE_STRONGS_TAGS[key] || {};

  return baseArray.map((rawText, idx) => {
    const verseNum = idx + 1;
    const headingMap = headingsForCh[verseNum];
    const heading = headingMap
      ? headingMap[langCode] || headingMap[langCode.split('-')[0]] || headingMap.en
      : undefined;

    const finalText =
      chMap[cleanVer]?.[idx] ||
      adaptVerseToLanguage(rawText, bookSlugOrId, chapter, verseNum, cleanVer);

    return {
      verse: verseNum,
      heading,
      text: finalText,
      strongsTags: strongsForCh[verseNum],
    };
  });
}

/**
 * Retrieve side-by-side Parallel Verses for any list of version IDs (e.g., ['nkjv', 'kjv', 'twi', 'tr-gk'])
 */
export function getParallelVerses(
  bookSlugOrId: string,
  chapter: number,
  versionIds: string[] = ['nkjv', 'kjv', 'twi', 'bsb']
): ParallelVerseRow[] | null {
  const nkjvChapter = getPrebundledChapter(bookSlugOrId, chapter, 'nkjv');
  if (!nkjvChapter) return null;

  const versionChapters: Record<string, VerseEntry[]> = {};
  for (const vId of versionIds) {
    versionChapters[vId] = getPrebundledChapter(bookSlugOrId, chapter, vId) || nkjvChapter;
  }

  return nkjvChapter.map((baseVerse, idx) => {
    const translations: Record<string, string> = {};
    for (const vId of versionIds) {
      translations[vId] = versionChapters[vId]?.[idx]?.text || baseVerse.text;
    }
    return {
      verse: baseVerse.verse,
      heading: baseVerse.heading,
      translations,
      strongsTags: baseVerse.strongsTags,
    };
  });
}

