export function getVersionById(versionId: string): BibleVersion {
  const clean = (versionId || 'nkjv').trim().toLowerCase();
  return (
    BIBLE_VERSIONS.find((v) => v.id.toLowerCase() === clean) ||
    BIBLE_VERSIONS.find((v) => v.shortCode.toLowerCase() === clean) ||
    BIBLE_VERSIONS.find((v) => v.langCode.toLowerCase() === clean) ||
    BIBLE_VERSIONS[0]
  );
}

export function getVersionsByLanguage(langCode: string): BibleVersion[] {
  const clean = (langCode || 'en').trim().toLowerCase();
  return BIBLE_VERSIONS.filter((v) => v.langCode.toLowerCase() === clean);
}

export function getLanguageByCode(langCode: string): LanguageEntry {
  const clean = (langCode || 'en').trim().toLowerCase();
  return (
    LANGUAGES_REGISTRY.find((l) => l.code.toLowerCase() === clean) ||
    LANGUAGES_REGISTRY.find((l) => l.code.toLowerCase().startsWith(clean)) ||
    LANGUAGES_REGISTRY[0]
  );
}
