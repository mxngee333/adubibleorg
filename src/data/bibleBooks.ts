export function getBookBySlug(slug: string): BibleBook | undefined {
  if (!slug) return undefined;
  const clean = slug.trim().toLowerCase().replace(/\s+/g, '_');
  const resolvedSlug = SLUG_ALIASES[clean] || clean;
  return (
    BIBLE_BOOKS.find((b) => b.slug === resolvedSlug) ||
    BIBLE_BOOKS.find((b) => b.id.toLowerCase() === clean) ||
    BIBLE_BOOKS.find((b) => b.names.en.toLowerCase().replace(/\s+/g, '_') === resolvedSlug)
  );
}

export function getBookById(id: string): BibleBook | undefined {
  if (!id) return undefined;
  const clean = id.trim().toUpperCase();
  return BIBLE_BOOKS.find((b) => b.id === clean) || getBookBySlug(id);
}

export function getBookByNumber(num: number): BibleBook | undefined {
  return BIBLE_BOOKS.find((b) => b.number === num);
}

export function getLocalizedBookName(bookIdOrSlug: string, langCode: string = 'en'): string {
  const book = getBookById(bookIdOrSlug) || getBookBySlug(bookIdOrSlug);
  if (!book) return bookIdOrSlug;
  if (book.names[langCode]) return book.names[langCode];
  const baseLang = langCode.split('-')[0];
  if (book.names[baseLang]) return book.names[baseLang];
  return book.names.en;
}

export function getBooksByTestament(testament: Testament): BibleBook[] {
  return BIBLE_BOOKS.filter((b) => b.testament === testament);
}

export function getBooksByCategory(category: BookCategory): BibleBook[] {
  return BIBLE_BOOKS.filter((b) => b.category === category);
}

export function getAdjacentChapter(
  bookSlugOrId: string,
  chapter: number,
  langCode: string = 'en'
): {
  prev: { bookSlug: string; bookId: string; bookName: string; chapter: number } | null;
  next: { bookSlug: string; bookId: string; bookName: string; chapter: number } | null;
} {
  const currentBook = getBookBySlug(bookSlugOrId) || getBookById(bookSlugOrId);
  if (!currentBook) {
    return { prev: null, next: null };
  }

  let prev: { bookSlug: string; bookId: string; bookName: string; chapter: number } | null = null;
  let next: { bookSlug: string; bookId: string; bookName: string; chapter: number } | null = null;

  if (chapter > 1) {
    prev = {
      bookSlug: currentBook.slug,
      bookId: currentBook.id,
      bookName: getLocalizedBookName(currentBook.id, langCode),
      chapter: chapter - 1,
    };
  } else if (currentBook.number > 1) {
    const prevBook = getBookByNumber(currentBook.number - 1);
    if (prevBook) {
      prev = {
        bookSlug: prevBook.slug,
        bookId: prevBook.id,
        bookName: getLocalizedBookName(prevBook.id, langCode),
        chapter: prevBook.chapters,
      };
    }
  }

  if (chapter < currentBook.chapters) {
    next = {
      bookSlug: currentBook.slug,
      bookId: currentBook.id,
      bookName: getLocalizedBookName(currentBook.id, langCode),
      chapter: chapter + 1,
    };
  } else if (currentBook.number < 66) {
    const nextBook = getBookByNumber(currentBook.number + 1);
    if (nextBook) {
      next = {
        bookSlug: nextBook.slug,
        bookId: nextBook.id,
        bookName: getLocalizedBookName(nextBook.id, langCode),
        chapter: 1,
      };
    }
  }

  return { prev, next };
}
