export function getStrongsEntry(code: string): StrongsLexiconEntry {
  const clean = (code || 'G2128').trim().toUpperCase();
  if (STRONGS_DICTIONARY[clean]) {
    return STRONGS_DICTIONARY[clean];
  }
  const isHeb = clean.startsWith('H');
  return {
    code: clean,
    language: isHeb ? 'Hebrew' : 'Greek',
    originalWord: isHeb ? 'דְּבַר־אֱלֹהִים' : 'λόγος Θεοῦ',
    transliteration: isHeb ? 'Devar-Elohim' : 'Logos Theou',
    phonetic: isHeb ? 'deh-var el-o-heem' : 'log-os theh-oo',
    partOfSpeech: 'Biblical Lexicon Root',
    rootWord: `Strong's Concordance ${clean} (${isHeb ? 'Masoretic Hebrew Lexicon' : 'Koine Greek New Testament Lexicon'})`,
    shortDefinition: `Biblical Root Term (${clean})`,
    fullDefinition: `Exhaustive Concordance entry ${clean}. Represents an original ${isHeb ? 'Hebrew/Aramaic Old Testament' : 'Koine Greek New Testament'} root word preserved in the canonical manuscripts.`,
    bdbOrThayer: isHeb
      ? 'Brown-Driver-Briggs Hebrew and English Lexicon of the Old Testament.'
      : "Thayer's Greek-English Lexicon of the New Testament.",
    kjvUsage: `Canonical occurrence indexed under ${clean}.`,
    occurrences: 12,
    keyVerses: ['Ephesians 1:3', 'Genesis 1:1', 'Psalm 23:1', 'John 1:1'],
    twiEquivalent: 'Twerɛ Kronkron Nsɛmfua Titire',
  };
}

export function getInterlinearForVerse(
  bookSlug: string,
  chapter: number,
  verse: number
): InterlinearWord[] | undefined {
  const key = `${bookSlug.toLowerCase()}_${chapter}`;
  return INTERLINEAR_VERSES[key]?.[verse];
}
